import json
from datetime import datetime, timedelta
from typing import Any, Literal

from pydantic import AliasChoices, Field, field_validator, model_validator
from pydantic import BaseModel as BaseSchema

from kraken.constants import LATENCY_TOLERANCE
from kraken.utilities import utc_now

ORDER_TYPE = Literal[
    "market",
    "limit",
    "iceberg",
    "stop-loss",
    "take-profit",
    "stop-loss-limit",
    "take-profit-limit",
    "trailing-stop",
    "trailing-stop-limit",
    "settle-position",
]
ORDER_DIRECTION = Literal["buy", "sell"]
ORDER_FLAG_SET = set(["post", "fcib", "fciq", "viqc"])
TRIGGER_TYPE = Literal["index", "last"]
STP_TYPE = Literal["cancel-newest", "cancel-oldest", "cancel-both"]
TIME_IN_FORCE = Literal["GTC", "IOC", "GTD", "PO"]


class ResponseErrorSchema(BaseSchema):
    """Error response from Kraken API.

    Contains error messages when order placement fails.
    """

    error: list[str] = Field(
        ...,
        description="List of error messages from the API.",
    )


class AddOrderRequest(BaseSchema):
    """Schema for Kraken AddOrder API request.

    This schema validates and prepares order data for submission to Kraken's
    AddOrder API endpoint. It is safe for concurrent async usage when properly
    serialized using the to_api_dict() method.

    Important Notes:
        - The 'nonce' parameter is automatically generated by the REST client
          at request signing time to prevent race conditions.
        - The 'deadline' parameter is NOT auto-generated during instantiation
          to prevent stale timestamps in async scenarios. The REST client
          will generate it at request time if None.
        - Use to_api_dict() to serialize for API submission (handles field
          aliasing like 'only_validate' -> 'validate').

    Thread Safety:
        This schema is thread-safe for instantiation and validation.
        Time-sensitive fields (nonce, deadline) are handled by the REST client
        at the last possible moment before request signing.

    Usage Examples:
        Basic market order:
        >>> order = AddOrderRequest(
        ...     ordertype="market",
        ...     type="buy",
        ...     volume=1.5,
        ...     pair="XBTUSD"
        ... )
        >>> data = order.to_api_dict()
        >>> response = client.request("AddOrder", data=data)

        Limit order with custom deadline:
        >>> from datetime import datetime, timedelta, timezone
        >>> deadline = (datetime.now(timezone.utc) + timedelta(seconds=10)).isoformat()
        >>> order = AddOrderRequest(
        ...     ordertype="limit",
        ...     type="sell",
        ...     volume=0.5,
        ...     pair="ETHUSD",
        ...     price="2000.50",
        ...     deadline=deadline
        ... )

        Validation only (no execution):
        >>> order = AddOrderRequest(
        ...     ordertype="limit",
        ...     type="buy",
        ...     volume=1,
        ...     pair="XBTUSD",
        ...     price="50000",
        ...     only_validate=True  # Test order validity without placing
        ... )

        Async usage (deadline computed at request time):
        >>> order = AddOrderRequest(
        ...     ordertype="market",
        ...     type="buy",
        ...     volume=1,
        ...     pair="XBTUSD"
        ... )
        >>> # Deadline remains None during queueing/delays
        >>> await asyncio.sleep(5)
        >>> # REST client will compute deadline at signing time
        >>> response = await client.arequest("AddOrder", data=order.to_api_dict())
    """

    userref: int | None = Field(
        default=None,
        description="This is an optional non-unique, numeric identifier for user metadata tracking. This field is mutually exclusive with `cl_ord_id` parameter.",
    )
    cl_ord_id: str | None = Field(
        default=None,
        description="Adds an alphanumeric client order identifier which uniquely identifies an open order for each client (long/short UUID or 18-ascii char). This field is mutually exclusive with `userref` parameter.",
    )
    ordertype: ORDER_TYPE = Field(..., description="The execution model of the order.")
    type: ORDER_DIRECTION = Field(..., description="Order direction (buy/sell).")
    volume: str | float | int = Field(
        ...,
        description="Order quantity in terms of the base asset; can be specified as 0 for closing margin orders to automatically fill the requisite quantity.",
    )
    displayvol: str | float | int | None = Field(
        default=None,
        description="For 'iceberg' orders only, it defines the quantity to show in the book while the rest of order quantity remains hidden. Minimum value is 1/15 of volume.",
    )
    pair: str = Field(..., description="Asset pair `id` or `altname`.")
    asset_class: str | None = Field(
        None, description="Required to be set as 'tokenized_asset' for non-crypto pairs (xstocks)."
    )
    price: str | None = Field(
        default=None,
        description="Limit price for 'limit' and 'iceberg' orders; trigger price for 'stop-loss', 'stop-loss-limit', 'take-profit', 'take-profit-limit', 'trailing-stop' and 'trailing-stop-limit' orders.",
    )
    price2: str | None = Field(
        default=None,
        description="Limit price for 'stop-loss-limit', 'take-profit-limit' and 'trailing-stop-limit' orders.",
    )
    trigger: TRIGGER_TYPE | None = Field(
        default=None,
        description="Price signal used to trigger 'stop-loss', 'stop-loss-limit', 'take-profit', 'take-profit-limit', 'trailing-stop' and 'trailing-stop-limit' orders.",
    )
    leverage: str | int | None = Field(None, description="Amount of desired leverage.")
    reduce_only: bool = Field(
        default=False,
        description="If `True`, order will only reduce a currently open position, not increase it or open a new position.",
    )
    stptype: STP_TYPE | None = Field(
        default=None,
        description="Self Trade Prevention (STP) behavior. If None, uses Kraken's default. Options: 'cancel-newest', 'cancel-oldest', 'cancel-both'.",
    )
    oflags: str | list[str] | set[str] | None = Field(
        default=None,
        description="Comma delimited list of order flags: 'post', 'fcib', 'fciq', 'viqc'.",
    )
    timeinforce: TIME_IN_FORCE | None = Field(
        default="GTC",
        description="Time-in-force of the order to specify how long it should remain in the order book before being cancelled.",
    )
    starttm: str | None = Field(
        default="0",
        description="Scheduled start time, can be specified as an absolute timestamp or as a number of seconds in the future.",
    )
    expiretm: str | None = Field(
        default="0",
        description="Expiry time on GTD orders can be set up to one month in future, it is specified as an absolute timestamp or as a number of seconds from now.",
    )
    deadline: str | None = Field(
        default=None,
        description="RFC3339 timestamp after which the matching engine should reject the new order request, in presence of latency or order queueing.",
    )
    only_validate: bool = Field(
        default=False,
        description="If True, validates order inputs without placing the order. Set to True for testing order parameters without execution.",
        validation_alias=AliasChoices("only_validate", "validate"),  # Accept both names
        serialization_alias="validate",  # Send as 'validate' to API
    )
    close_ordertype: ORDER_TYPE | None = Field(
        default=None,
        description="Conditional close order type for positions. Used with 'close_price' and optionally 'close_price2' to create an OCO (One-Cancels-Other) order.",
    )
    close_price: str | None = Field(
        default=None,
        description="Conditional close order price. Required when 'close_ordertype' is specified.",
    )
    close_price2: str | None = Field(
        default=None,
        description="Conditional close order secondary price for stop-loss-limit or take-profit-limit orders.",
    )

    @field_validator("ordertype", mode="before")
    @classmethod
    def lowercase_order(cls, value: str) -> str:
        return value.lower().strip()

    @field_validator("volume", mode="before")
    @classmethod
    def string_volume(cls, value: str | float | int) -> str:
        return str(value)

    @field_validator("displayvol", mode="before")
    @classmethod
    def floor_display_volume(cls, value: str | float | int | None, info) -> str | None:
        if value is None:
            return None
        order_volume = float(info.data.get("volume"))
        floor_volume = order_volume / 15.0
        if float(value) > order_volume:
            return str(order_volume)
        elif float(value) < floor_volume:
            return str(floor_volume)
        else:
            return str(value)

    @field_validator("leverage", mode="before")
    @classmethod
    def string_leverage(cls, value: str | float | None) -> str | None:
        if value is None:
            return None
        return str(value)

    @field_validator("oflags", mode="before")
    @classmethod
    def concat_order_flags(cls, value: str | list[str] | set[str] | None) -> str | None:
        if value is None:
            return None
        if isinstance(value, str):
            splits = value.split(",")
            if len(splits) > 1:
                value = set(splits)
            else:
                value = {value}
        elif isinstance(value, list):
            value = set(value)
        value = ORDER_FLAG_SET.intersection(value)
        return ",".join(value) if len(value) > 0 else None

    @field_validator("timeinforce", mode="before")
    @classmethod
    def capitalize_time_in_force(cls, value: str) -> str:
        return value.upper().strip()

    @field_validator("deadline", mode="after")
    @classmethod
    def validate_deadline(cls, value: str | None) -> str | None:
        """Validate deadline format and timezone information.

        Note: Deadline is NOT auto-generated here to prevent race conditions.
        The REST client will generate the deadline at request signing time
        if None is provided, ensuring accurate timing for async operations.
        """
        if value is None:
            return None

        deadline = datetime.fromisoformat(value)
        if deadline.tzinfo is None:
            raise ValueError(
                "Deadline must include timezone information (RFC3339 format). "
                "Example: '2025-01-15T12:00:00+00:00' or use 'Z' for UTC."
            )

        # Validate deadline is bounded between 2-60 seconds from now
        now = utc_now()
        min_t, max_t = now + timedelta(seconds=2), now + timedelta(seconds=60)
        deadline_utc = deadline.astimezone(now.tzinfo)

        if deadline_utc < min_t:
            deadline_utc = min_t
        elif deadline_utc > max_t:
            deadline_utc = max_t

        return deadline_utc.isoformat()

    @model_validator(mode="after")
    def validate_field_dependencies(self) -> "AddOrderRequest":
        """Validate field dependencies for different order types."""
        # Iceberg orders require price
        if self.ordertype == "iceberg" and self.price is None:
            raise ValueError("Iceberg orders require 'price' field")

        # Limit orders require price
        if self.ordertype == "limit" and self.price is None:
            raise ValueError("Limit orders require 'price' field")

        # Stop-loss and take-profit orders require price
        if self.ordertype in ["stop-loss", "take-profit", "trailing-stop"] and self.price is None:
            raise ValueError(f"{self.ordertype} orders require 'price' field")

        # Stop-loss-limit and take-profit-limit require both price and price2
        if self.ordertype in ["stop-loss-limit", "take-profit-limit", "trailing-stop-limit"]:
            if self.price is None or self.price2 is None:
                raise ValueError(
                    f"{self.ordertype} orders require both 'price' and 'price2' fields"
                )

        # Conditional close orders require close_price
        if self.close_ordertype is not None and self.close_price is None:
            raise ValueError("Conditional close orders require 'close_price' field")

        # Conditional close limit orders require close_price2
        if self.close_ordertype in ["stop-loss-limit", "take-profit-limit"]:
            if self.close_price2 is None:
                raise ValueError(
                    f"Conditional close {self.close_ordertype} orders require 'close_price2' field"
                )

        # GTD orders require expiretm
        if self.timeinforce == "GTD" and (self.expiretm is None or self.expiretm == "0"):
            raise ValueError("GTD (Good-Til-Date) orders require 'expiretm' field")

        # userref and cl_ord_id are mutually exclusive
        if self.userref is not None and self.cl_ord_id is not None:
            raise ValueError("'userref' and 'cl_ord_id' are mutually exclusive")

        return self

    def to_api_dict(self, **kwargs) -> dict[str, Any]:
        """Serialize order to dict for Kraken API submission.

        This method handles proper field aliasing and exclusion of None values
        for API compatibility. Use this method when passing orders to the REST client.

        Args:
            exclude_none: If True, removes fields with None values from output.
                         Default is True for Kraken API compatibility.

        Returns:
            Dictionary suitable for Kraken API AddOrder endpoint

        Example:
            >>> order = AddOrderRequest(
            ...     ordertype="limit",
            ...     type="buy",
            ...     volume=1.5,
            ...     pair="XBTUSD",
            ...     price="50000"
            ... )
            >>> data = order.to_api_dict()
            >>> # Pass to REST client
            >>> response = client.request("AddOrder", data=data)
        """
        return self.model_dump(
            by_alias=kwargs.pop("by_alias", True),
            exclude_none=kwargs.pop("exclude_none", True),
            **kwargs,
        )

    @staticmethod
    def compute_deadline(latency_tolerance: int = LATENCY_TOLERANCE) -> str:
        """Compute a deadline timestamp for order submission.

        This is a utility method that should be called by the REST client
        at request signing time, not during order instantiation.

        Args:
            latency_tolerance: Seconds to add to current time for deadline

        Returns:
            RFC3339 formatted deadline string
        """
        now = utc_now()
        deadline = now + timedelta(seconds=latency_tolerance)
        min_t, max_t = now + timedelta(seconds=2), now + timedelta(seconds=60)
        if deadline < min_t:
            deadline = min_t
        elif deadline > max_t:
            deadline = max_t
        return deadline.isoformat()


class AddOrderSuccess(BaseSchema):
    """Successful AddOrder response from Kraken API.

    Contains order details and transaction IDs when an order is successfully
    placed or validated.
    """

    txid: list[str] = Field(
        ...,
        description="18-character transaction IDs for the order(s) placed.",
    )
    descr: dict = Field(
        ...,
        description="Order description containing 'order' and optionally 'close' fields.",
    )

    @property
    def order_description(self) -> str:
        """Get the order description string."""
        return self.descr.get("order", "")

    @property
    def close_description(self) -> str | None:
        """Get the conditional close order description, if any."""
        return self.descr.get("close")


class AddOrderResponse(BaseSchema):
    """Combined response wrapper for AddOrder API calls.

    This wrapper handles both success and error cases from the Kraken API.
    Use the `is_success` property to determine the outcome and access the
    appropriate `success` or `error` attribute.
    """

    success: AddOrderSuccess | None = Field(
        default=None,
        description="Success response data, present when order placement succeeds.",
    )
    error: ResponseErrorSchema | None = Field(
        default=None,
        description="Error response data, present when order placement fails.",
    )

    @property
    def is_success(self) -> bool:
        """Check if the response indicates success."""
        return self.success is not None

    @classmethod
    def from_response(cls, response: dict | str) -> "AddOrderResponse":
        """Parse a Kraken API response into the appropriate response model.

        Args:
            response: Either a JSON string or dict containing the API response

        Returns:
            AddOrderResponse with either success or error data populated

        Raises:
            ValueError: If the response format is invalid
        """
        if isinstance(response, str):
            response = json.loads(response)
        errors = response.get("error", [])
        if errors:
            error_data = ResponseErrorSchema(error=errors)
            return cls(error=error_data)

        result = response.get("result")
        if not result:
            raise ValueError("Response missing 'result' field")
        success_data = AddOrderSuccess(
            txid=result["txid"],
            descr=result["descr"],
        )
        return cls(success=success_data)


class AmendOrderRequest(BaseSchema):
    """Schema for Kraken AmendOrder API request.

    This schema validates and prepares order amendment data for submission to
    Kraken's AmendOrder API endpoint. It is safe for concurrent async usage when
    properly serialized using the to_api_dict() method.

    Important Notes:
        - The 'nonce' parameter is automatically generated by the REST client
          at request signing time to prevent race conditions.
        - The 'deadline' parameter is NOT auto-generated during instantiation
          to prevent stale timestamps in async scenarios. The REST client
          will generate it at request time if None.
        - Either 'txid' or 'cl_ord_id' must be provided to identify the order.
        - Use to_api_dict() to serialize for API submission.

    Thread Safety:
        This schema is thread-safe for instantiation and validation.
        Time-sensitive fields (nonce, deadline) are handled by the REST client
        at the last possible moment before request signing.

    Usage Examples:
        Amend order quantity by txid:
        >>> amend = AmendOrderRequest(
        ...     txid="OUF4EM-FRGI2-MQMWZD",
        ...     order_qty=2.5
        ... )
        >>> data = amend.to_api_dict()
        >>> response = client.request("AmendOrder", data=data)

        Amend limit price by client order ID:
        >>> amend = AmendOrderRequest(
        ...     cl_ord_id="my-order-123",
        ...     limit_price="51000.50"
        ... )
        >>> response = client.request("AmendOrder", data=amend.to_api_dict())

        Amend with relative pricing:
        >>> amend = AmendOrderRequest(
        ...     txid="ABC-123",
        ...     limit_price="+100",  # Add 100 to current reference price
        ...     trigger_price="-50%"  # Subtract 50% from reference price
        ... )

        Amend iceberg order display quantity:
        >>> amend = AmendOrderRequest(
        ...     txid="OUF4EM-FRGI2-MQMWZD",
        ...     display_qty=5.0,
        ...     pair="XBTUSD"
        ... )

        Async usage (deadline computed at request time):
        >>> amend = AmendOrderRequest(
        ...     txid="OUF4EM-FRGI2-MQMWZD",
        ...     order_qty=1.5
        ... )
        >>> # Deadline remains None during queueing/delays
        >>> await asyncio.sleep(5)
        >>> # REST client will compute deadline at signing time
        >>> response = await client.arequest("AmendOrder", data=amend.to_api_dict())
    """

    txid: str | None = Field(
        default=None,
        description="The Kraken identifier for the order to be amended. Either txid or cl_ord_id is required.",
    )
    cl_ord_id: str | None = Field(
        default=None,
        description="The client identifier for the order to be amended. Either txid or cl_ord_id is required.",
    )
    order_qty: str | float | int | None = Field(
        default=None,
        description="The new order quantity in terms of the base asset.",
    )
    display_qty: str | float | int | None = Field(
        default=None,
        description="For iceberg orders only, it defines the new quantity to show in the book while the rest of order quantity remains hidden. Minimum value is 1/15 of remaining order quantity.",
    )
    limit_price: str | None = Field(
        default=None,
        description="The new limit price restriction on the order (for order types that support limit price only). Supports relative pricing: +/- prefix to add/subtract from reference price, % suffix for percentage adjustments.",
    )
    trigger_price: str | None = Field(
        default=None,
        description="The new trigger price to activate the order (for triggered order types only). Supports relative pricing: +/- prefix to add/subtract from reference price, % suffix for percentage adjustments.",
    )
    pair: str | None = Field(
        default=None,
        description="The pair is required on amends for non-crypto pairs (xstocks). Provide the pair symbol for tokenized assets.",
    )
    post_only: bool = Field(
        default=False,
        description="An optional flag for limit_price amends. If true, the limit price change will be rejected if the order cannot be posted passively in the book.",
    )
    deadline: str | None = Field(
        default=None,
        description="RFC3339 timestamp after which the matching engine should reject the amend request, in presence of latency or order queueing.",
    )

    @field_validator("order_qty", mode="before")
    @classmethod
    def string_order_qty(cls, value: str | float | int | None) -> str | None:
        if value is None:
            return None
        return str(value)

    @field_validator("display_qty", mode="before")
    @classmethod
    def floor_display_qty(cls, value: str | float | int | None, info) -> str | None:
        if value is None:
            return None
        order_qty = info.data.get("order_qty") # If order_qty is provided, use it for floor calc
        if order_qty is not None:
            order_volume = float(order_qty)
            floor_volume = order_volume / 15.0
            if float(value) > order_volume:
                return str(order_volume)
            elif float(value) < floor_volume:
                return str(floor_volume)
        return str(value)

    @field_validator("deadline", mode="after")
    @classmethod
    def validate_deadline(cls, value: str | None) -> str | None:
        """Validate deadline format and timezone information.

        Note: Deadline is NOT auto-generated here to prevent race conditions.
        The REST client will generate the deadline at request signing time
        if None is provided, ensuring accurate timing for async operations.
        """
        if value is None:
            return None
        deadline = datetime.fromisoformat(value)
        if deadline.tzinfo is None:
            raise ValueError(
                "Deadline must include timezone information (RFC3339 format). "
                "Example: '2025-01-15T12:00:00+00:00' or use 'Z' for UTC."
            )
        now = utc_now()
        min_t, max_t = now + timedelta(seconds=2), now + timedelta(seconds=60)
        deadline_utc = deadline.astimezone(now.tzinfo)
        if deadline_utc < min_t:
            deadline_utc = min_t
        elif deadline_utc > max_t:
            deadline_utc = max_t
        return deadline_utc.isoformat()

    @model_validator(mode="after")
    def validate_field_dependencies(self) -> "AmendOrderRequest":
        """Validate field dependencies for amend requests."""
        if self.txid is None and self.cl_ord_id is None:
            raise ValueError("Either 'txid' or 'cl_ord_id' must be provided")
        if self.txid is not None and self.cl_ord_id is not None:
            raise ValueError("'txid' and 'cl_ord_id' are mutually exclusive")
        return self

    def to_api_dict(self, **kwargs) -> dict[str, Any]:
        """Serialize amend request to dict for Kraken API submission.

        This method handles proper field aliasing and exclusion of None values
        for API compatibility. Use this method when passing amend requests to
        the REST client.

        Args:
            exclude_none: If True, removes fields with None values from output.
                         Default is True for Kraken API compatibility.

        Returns:
            Dictionary suitable for Kraken API AmendOrder endpoint

        Example:
            >>> amend = AmendOrderRequest(
            ...     txid="OUF4EM-FRGI2-MQMWZD",
            ...     order_qty=2.5,
            ...     limit_price="51000"
            ... )
            >>> data = amend.to_api_dict()
            >>> # Pass to REST client
            >>> response = client.request("AmendOrder", data=data)
        """
        return self.model_dump(
            by_alias=kwargs.pop("by_alias", True),
            exclude_none=kwargs.pop("exclude_none", True),
            **kwargs,
        )

    @staticmethod
    def compute_deadline(latency_tolerance: int = LATENCY_TOLERANCE) -> str:
        """Compute a deadline timestamp for amend request submission.

        This is a utility method that should be called by the REST client
        at request signing time, not during amend instantiation.

        Args:
            latency_tolerance: Seconds to add to current time for deadline

        Returns:
            RFC3339 formatted deadline string
        """
        now = utc_now()
        deadline = now + timedelta(seconds=latency_tolerance)
        min_t, max_t = now + timedelta(seconds=2), now + timedelta(seconds=60)
        if deadline < min_t:
            deadline = min_t
        elif deadline > max_t:
            deadline = max_t
        return deadline.isoformat()


